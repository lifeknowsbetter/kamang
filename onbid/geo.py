SIDO_CENTER = {k: (sum(v[0] for v in d.values()) / len(d), sum(v[1] for v in d.values()) / len(d)) for k, d in C.items()}

def km(a, b):
    la1, lo1, la2, lo2 = map(math.radians, (*a, *b))
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 6371 * 2 * math.asin(math.sqrt(h))

def dist_from_sanbon(sido_sgk_emd):
    """('거리km', '정확도') — 시군구까지 맞으면 'sgg', 시도만 맞으면 'sido', 모르면 (None,None)"""
    p = (sido_sgk_emd or '').split()
    if not p or p[0] not in C: return None, None
    if len(p) >= 2 and p[1] in C[p[0]]:
        return round(km(ORIGIN, C[p[0]][p[1]])), 'sgg'
    return round(km(ORIGIN, SIDO_CENTER[p[0]])), 'sido'

BANDS = ('근거리(≤20km)', '수도권 1시간권(≤50km)', '1~2시간(≤100km)', '2~3시간(≤200km)', '원거리(200km↑)')


def band_idx(d):
    """0(가까움)~4(멂). 위치를 모르면 5."""
    if d is None:
        return 5
    return 0 if d <= 20 else 1 if d <= 50 else 2 if d <= 100 else 3 if d <= 200 else 4


def band(d):
    return '위치 불명' if d is None else BANDS[band_idx(d)]


def loc_of(row):
    """행의 소재지 문자열. sidoSgkEmd가 '-'·빈 값이면 물건명 앞 토큰('시도 시군구 읍면동', '시 구'면 4토큰)으로 만든다.
    이름이 시도로 시작하지 않으면(권리형 동산 등) ''를 돌려 이전처럼 위치 불명으로 둔다."""
    s = (row.get('sidoSgkEmd') or '').strip()
    if s and s != '-':
        return s
    p = (row.get('onbidCltrNm') or '').split()
    if len(p) >= 3 and p[0] in C:
        return ' '.join(p[:4] if len(p) >= 4 and p[1].endswith('시') and p[2].endswith('구') else p[:3])
    return ''


def of(row):
    """검색 행 → (km, 구간 이름). 시도만 맞으면 시도 중심 기준."""
    d, _ = dist_from_sanbon(loc_of(row))
    return d, band(d)
